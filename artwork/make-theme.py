#!/usr/bin/env python3
"""Generate the themed config files from the termOS palette
(rootfs/usr/local/lib/termos/termosui/palette.py), the one place colours live.

  python3 artwork/make-theme.py            write the files
  python3 artwork/make-theme.py --check    fail if any file is out of date
"""
import os
import runpy
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rootfs")
# loaded by path: importing the package would need GTK on the build machine
palette = runpy.run_path(os.path.join(ROOT, "usr", "local", "lib", "termos", "termosui", "palette.py"))
C, MONO_FONT, UI_FONT = palette["COLORS"], palette["MONO_FONT"], palette["UI_FONT"]
gtk_named_colors = palette["gtk_named_colors"]

GEN = "Generated by artwork/make-theme.py from termosui/palette.py"
SKEL = "etc/skel/.config"


def nohash(name):
    return C[name].lstrip("#")


def gtk_css():
    return f"/* {GEN} */\n{gtk_named_colors()}"


def gtk_settings():
    return f"""[Settings]
gtk-application-prefer-dark-theme=1
gtk-theme-name=adw-gtk3-dark
gtk-font-name={UI_FONT} 11
gtk-icon-theme-name=Papirus-Dark
"""


def labwc():
    return f"""# {GEN}
# Touch-sized title bars and menus
window.titlebar.padding.height: 2
window.titlebar.padding.width: 4
window.button.width: 48
window.button.height: 40
window.button.spacing: 6
window.button.hover.bg.color: {C['raised']}
window.button.hover.bg.corner-radius: 10
menu.width.min: 260
menu.width.max: 420
menu.items.padding.x: 16
menu.items.padding.y: 10
menu.overlap.x: 0

window.active.title.bg.color: {C['mantle']}
window.inactive.title.bg.color: {C['crust']}
window.active.label.text.color: {C['text']}
window.inactive.label.text.color: {C['faint']}
window.active.button.unpressed.image.color: {C['text']}
window.inactive.button.unpressed.image.color: {C['faint']}
window.active.border.color: {C['raised']}
window.inactive.border.color: {C['mantle']}
menu.items.bg.color: {C['base']}
menu.items.text.color: {C['text']}
menu.items.active.bg.color: {C['hover']}
menu.items.active.text.color: {C['bright']}
menu.border.color: {C['hover']}
menu.separator.color: {C['hover']}
osd.bg.color: {C['base']}
osd.label.text.color: {C['text']}
osd.border.color: {C['hover']}
"""


def foot():
    normal = ["hover", "red", "green", "yellow", "accent", "mauve", "teal", "text"]
    bright = ["faint", "pink", "green", "orange", "accent", "pink", "teal", "bright"]
    lines = [f"# {GEN}", "[main]", f"font={MONO_FONT}:size=12", "pad=8x8", "",
             "[scrollback]", "lines=10000", "", "[colors-dark]",
             f"background={nohash('base')}", f"foreground={nohash('text')}",
             f"cursor={nohash('base')} {nohash('accent')}",
             f"selection-background={nohash('hover')}", f"selection-foreground={nohash('bright')}"]
    lines += [f"regular{i}={nohash(c)}" for i, c in enumerate(normal)]
    lines += [f"bright{i}={nohash(c)}" for i, c in enumerate(bright)]
    return "\n".join(lines) + "\n"


def mako():
    return f"""# {GEN}
# termOS notifications - tap to dismiss
font={UI_FONT} 12
background-color={C['card']}f2
text-color={C['text']}
border-color={C['hover']}
progress-color=over {C['raised']}
border-size=1
border-radius=14
padding=14
margin=12
width=380
icon-path=/usr/share/icons/Papirus-Dark
max-icon-size=48
default-timeout=6000
anchor=top-center
on-touch=dismiss

[urgency=critical]
border-color={C['red']}
default-timeout=0
"""


BUTTONS = {
    "close": "M14 14 L26 26 M26 14 L14 26",
    "iconify": "M13 25 H27",
    "max": "M13 13 H27 V27 H13 Z",
    "max_toggled": "M13 17 H23 V27 H13 Z M17 13 H27 V23",
    "menu": "M12 15 H28 M12 20 H28 M12 25 H28",
}


def title_button(path, color):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40" viewBox="0 0 40 40">'
            f'<path d="{path}" fill="none" stroke="{color}" stroke-width="2.4" '
            f'stroke-linecap="round" stroke-linejoin="round"/></svg>\n')


def outputs():
    files = {
        f"{SKEL}/gtk-3.0/gtk.css": gtk_css(),
        f"{SKEL}/gtk-3.0/settings.ini": gtk_settings(),
        f"{SKEL}/labwc/themerc-override": labwc(),
        f"{SKEL}/foot/foot.ini": foot(),
        f"{SKEL}/mako/config": mako(),
        "usr/share/themes/termOS/labwc/themerc": f"# {GEN}\nborder.width: 1\n",
    }
    for name, path in BUTTONS.items():
        for state, col in (("active", "text"), ("inactive", "faint")):
            files[f"usr/share/themes/termOS/labwc/{name}-{state}.svg"] = title_button(path, C[col])
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, text in outputs().items():
        path = os.path.join(ROOT, rel)
        try:
            with open(path, encoding="utf-8") as f:
                if f.read() == text:
                    continue
        except FileNotFoundError:
            pass
        stale.append(rel)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    for rel in stale:
        print(("out of date: " if check else "wrote ") + rel)
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
